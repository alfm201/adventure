import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = resolve(import.meta.dirname, '..');
export async function imageManifest({ check = false } = {}) {
  const files = (await readdir(resolve(root, 'public/assets'))).filter(name => name.endsWith('.png')).sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));
  const entries = {};
  for (const name of files) {
    const bytes = await readFile(resolve(root, 'public/assets', name));
    entries[name] = { sha256: createHash('sha256').update(bytes).digest('hex'), bytes: bytes.length };
  }
  const output = '// Generated by scripts/image-manifest.mjs. Do not edit.\nexport const IMAGE_MANIFEST = ' + JSON.stringify(entries, null, 2) + ';\n';
  const target = resolve(root, 'src/content/image-manifest.js');
  const previous = (await readFile(target, 'utf8').catch(() => '')).replace(/\r\n/g, '\n');
  if (check && previous !== output) throw Error('Image manifest is out of date. Run: npm run assets:generate');
  if (!check && previous !== output) await writeFile(target, output);
  return { files: files.length, bytes: Object.values(entries).reduce((sum, entry) => sum + entry.bytes, 0), changed: previous !== output };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try { console.log(JSON.stringify(await imageManifest({ check: process.argv.includes('--check') }))); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
