import fs from 'node:fs';
import {createHash} from 'node:crypto';

// JSEP has no public buffer-cache option in this bundled runtime. Keep the
// upstream arithmetic, buffer sizes, shader code and intra-run pooling unchanged.
// Expose a Worker-local hook to trim unused buffers AFTER output readback.
const target = new URL('../public/runtime/onnxruntime-web/1.30.0/ort.all.min.mjs', import.meta.url);
const upstreamSha = '2e4a0eae53c3f246e26423aaca493d3bfc22ce524894f27519a9ec4a14e6397a';
const notice = '/* LYRA JSEP cache policy v2: post-run unused-buffer trimming only; arithmetic and intra-run pooling unchanged. Generated by scripts/lyra-runtime-cache.mjs. */\n';
const anchor = 'this.sessionCount=0}upload(e,n)';
const replacement = 'this.sessionCount=0;globalThis.__lyraTrimGpuCache=(limit=268435456)=>{let retained=0,released=0;for(const[size,buffers]of [...this.freeBuffers.entries()].sort((a,b)=>a[0]-b[0]))for(let index=buffers.length-1;index>=0;index--){const buffer=buffers[index];if(retained+buffer.size>limit){buffers.splice(index,1);released+=buffer.size;buffer.destroy()}else retained+=buffer.size}return{retainedBytes:retained,releasedBytes:released}}}upload(e,n)';
const hash = value => createHash('sha256').update(value).digest('hex');
const current = fs.readFileSync(target, 'utf8');
const source = current.startsWith(notice) ? current.slice(notice.length).replace(replacement, anchor) : current;
if (hash(source) !== upstreamSha || source.split(anchor).length !== 2) throw Error('Unexpected upstream ONNX Runtime; review the cache patch before upgrading.');
const expected = notice + source.replace(anchor, replacement);
if (process.argv.includes('--check')) {
  if (current !== expected) throw Error('LYRA runtime cache patch is missing or changed.');
} else fs.writeFileSync(target, expected);
console.log(JSON.stringify({policy:'lyra-postrun-v2',upstreamSha256:upstreamSha,patchedSha256:hash(expected),maxUnusedStorageCacheBytes:268435456}));
